-- Références géographiques uniquement : aucune zone, flotte, date ou réservation créée.
CREATE TABLE itineraire_propose (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origine VARCHAR(255) NOT NULL,
    destination VARCHAR(255) NOT NULL,
    CONSTRAINT ck_itineraire_propose_lieux CHECK (
        origine ~ '[^[:space:]]' AND origine = btrim(origine)
        AND destination ~ '[^[:space:]]' AND destination = btrim(destination)
    )
);

-- Le sens compte : Bruxelles–Mons et Mons–Bruxelles sont deux références distinctes.
CREATE UNIQUE INDEX uq_itineraire_propose_lieux
    ON itineraire_propose(lower(btrim(origine)), lower(btrim(destination)));

