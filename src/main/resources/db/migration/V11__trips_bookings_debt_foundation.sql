ALTER TABLE vehicule ADD CONSTRAINT uq_vehicule_zone UNIQUE(id,zone_id);
CREATE TABLE trajet (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 zone_id bigint NOT NULL REFERENCES zone(id),
 vehicule_id bigint NOT NULL,
 organisateur_id bigint NOT NULL REFERENCES client(id),
 depart timestamptz NOT NULL, arrivee timestamptz NOT NULL,
 type varchar(10) NOT NULL CHECK(type IN ('PUBLIC','PRIVE')),
 statut varchar(12) NOT NULL DEFAULT 'PLANIFIE' CHECK(statut IN ('PLANIFIE','COMPLET','ANNULE')),
 CONSTRAINT uq_trajet_owner UNIQUE(id,organisateur_id),
 CONSTRAINT ck_trajet_interval CHECK(arrivee>depart),
 CONSTRAINT fk_trajet_vehicle_zone FOREIGN KEY(vehicule_id,zone_id) REFERENCES vehicule(id,zone_id)
);
CREATE INDEX ix_trajet_zone_depart ON trajet(zone_id,depart,id);
CREATE INDEX ix_trajet_vehicle_interval ON trajet(vehicule_id,depart,arrivee) WHERE statut<>'ANNULE';
CREATE INDEX ix_trajet_organisateur ON trajet(organisateur_id,id);
CREATE TABLE reservation (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trajet_id bigint NOT NULL REFERENCES trajet(id),
 client_id bigint NOT NULL REFERENCES client(id),
 statut varchar(12) NOT NULL DEFAULT 'EN_ATTENTE' CHECK(statut IN ('EN_ATTENTE','CONFIRMEE','ANNULEE')),
 CONSTRAINT uq_reservation_client UNIQUE(trajet_id,client_id)
);
CREATE INDEX ix_booking_client ON reservation(client_id,id);
CREATE INDEX ix_reservation_capacity ON reservation(trajet_id,statut);
-- Read by booking eligibility now, settled by the payment module. No expiry.
CREATE TABLE dette_trajet (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trajet_id bigint NOT NULL UNIQUE REFERENCES trajet(id),
 client_id bigint NOT NULL REFERENCES client(id),
 montant numeric(10,2) NOT NULL DEFAULT 80.00 CHECK(montant=80.00),
 regle numeric(10,2) NOT NULL DEFAULT 0 CHECK(regle>=0 AND regle<=montant),
 statut varchar(12) NOT NULL DEFAULT 'ACTIVE',
 CONSTRAINT ck_dette_statut CHECK((statut='ACTIVE' AND regle<montant) OR (statut='REGULARISEE' AND regle=montant))
);
ALTER TABLE dette_trajet ADD CONSTRAINT fk_dette_organisateur FOREIGN KEY(trajet_id,client_id) REFERENCES trajet(id,organisateur_id);
CREATE INDEX ix_dette_active_client ON dette_trajet(client_id) WHERE statut='ACTIVE';
CREATE FUNCTION verifier_intervalle_trajet() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
 PERFORM 1 FROM vehicule WHERE id=NEW.vehicule_id FOR UPDATE;
 IF NEW.statut<>'ANNULE' AND EXISTS(
  SELECT 1 FROM trajet t WHERE t.id<>NEW.id AND t.vehicule_id=NEW.vehicule_id AND t.statut<>'ANNULE'
   AND t.depart<NEW.arrivee+interval '15 minutes' AND t.arrivee>NEW.depart-interval '15 minutes'
 ) THEN RAISE EXCEPTION 'Vehicle schedule conflict' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_trajet_interval BEFORE INSERT OR UPDATE OF vehicule_id,depart,arrivee,statut ON trajet
 FOR EACH ROW EXECUTE FUNCTION verifier_intervalle_trajet();
CREATE FUNCTION verifier_capacite_reservation() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE etat varchar(12);
BEGIN
 SELECT statut INTO etat FROM trajet WHERE id=NEW.trajet_id FOR UPDATE;
 IF NEW.statut='CONFIRMEE' AND (etat='ANNULE' OR
   (SELECT count(*) FROM reservation WHERE trajet_id=NEW.trajet_id AND statut='CONFIRMEE' AND id<>NEW.id)>=4)
 THEN RAISE EXCEPTION 'Trip capacity or state conflict' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_reservation_capacity BEFORE INSERT OR UPDATE ON reservation
 FOR EACH ROW EXECUTE FUNCTION verifier_capacite_reservation();
