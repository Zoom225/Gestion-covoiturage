 END IF;
END $$;
-- Retain the existing capacity trigger, strengthening closed-state checks additively.
CREATE OR REPLACE FUNCTION verifier_capacite_reservation() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE etat varchar(12); nouvelle_confirmation boolean;
BEGIN
 SELECT statut INTO etat FROM trajet WHERE id=NEW.trajet_id FOR UPDATE;
 IF TG_OP='INSERT' THEN nouvelle_confirmation=NEW.statut='CONFIRMEE';
 ELSE nouvelle_confirmation=NEW.statut='CONFIRMEE' AND OLD.statut<>'CONFIRMEE'; END IF;
 IF nouvelle_confirmation AND (etat<>'PLANIFIE' OR
   (SELECT count(*) FROM reservation WHERE trajet_id=NEW.trajet_id AND statut='CONFIRMEE' AND id<>NEW.id)>=4)
 THEN RAISE EXCEPTION 'Trip capacity or state conflict' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
ALTER TABLE trajet ADD COLUMN traite_j1_le timestamptz,
 ADD CONSTRAINT ck_j1_public CHECK(traite_j1_le IS NULL OR type='PUBLIC');
CREATE TABLE paiement_place (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_id bigint NOT NULL UNIQUE REFERENCES reservation(id),
 cle_idempotence uuid NOT NULL UNIQUE,
 montant numeric(10,2) NOT NULL CHECK(montant=20.00),
 mode varchar(20) NOT NULL CHECK(mode='SIMULATION'),
 valide_le timestamptz NOT NULL
);
CREATE TABLE paiement_dette (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dette_id bigint NOT NULL REFERENCES dette_trajet(id),
 cle_idempotence uuid NOT NULL UNIQUE,
 montant numeric(10,2) NOT NULL CHECK(montant>0 AND montant<=80.00),
 mode varchar(20) NOT NULL CHECK(mode='SIMULATION'),
 valide_le timestamptz NOT NULL
);
CREATE INDEX ix_paiement_dette ON paiement_dette(dette_id,id);
CREATE FUNCTION verifier_paiement_confirmation() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE booking bigint; state varchar(12); paid boolean;
BEGIN
 IF TG_TABLE_NAME='reservation' THEN
  IF TG_OP='DELETE' THEN booking=OLD.id; ELSE booking=NEW.id; END IF;
 ELSE
  IF TG_OP='DELETE' THEN booking=OLD.reservation_id; ELSE booking=NEW.reservation_id; END IF;
 END IF;
 SELECT statut INTO state FROM reservation WHERE id=booking;
 IF NOT FOUND THEN RETURN NULL; END IF;
 SELECT EXISTS(SELECT 1 FROM paiement_place WHERE reservation_id=booking) INTO paid;
 IF (state='CONFIRMEE')<>paid THEN
  RAISE EXCEPTION 'Payment and confirmation must be atomic' USING ERRCODE='23514';
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_confirmation_paid AFTER INSERT OR UPDATE OR DELETE ON reservation
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verifier_paiement_confirmation();
CREATE CONSTRAINT TRIGGER trg_payment_confirmed AFTER INSERT OR UPDATE OR DELETE ON paiement_place
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verifier_paiement_confirmation();
CREATE FUNCTION verifier_reglement_dette() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE debt bigint; total numeric; settled numeric;
BEGIN
 IF TG_TABLE_NAME='dette_trajet' THEN
  IF TG_OP='DELETE' THEN debt=OLD.id; ELSE debt=NEW.id; END IF;
 ELSE
  IF TG_OP='DELETE' THEN debt=OLD.dette_id; ELSE debt=NEW.dette_id; END IF;
 END IF;
 SELECT regle INTO settled FROM dette_trajet WHERE id=debt;
 IF NOT FOUND THEN RETURN NULL; END IF;
 SELECT coalesce(sum(montant),0) INTO total FROM paiement_dette WHERE dette_id=debt;
 IF total<>settled THEN
  RAISE EXCEPTION 'Debt balance must match settlements' USING ERRCODE='23514';
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_debt_balance AFTER INSERT OR UPDATE OR DELETE ON dette_trajet
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verifier_reglement_dette();
CREATE CONSTRAINT TRIGGER trg_settlement_balance AFTER INSERT OR UPDATE OR DELETE ON paiement_dette
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verifier_reglement_dette();
