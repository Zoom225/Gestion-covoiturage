-- Comptes techniques distincts des catégories métier (cahier final, section 11).
-- Aucun identifiant ni mot de passe par défaut.
CREATE TABLE compte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant VARCHAR(100) NOT NULL CONSTRAINT uk_compte_identifiant UNIQUE,
    password_hash VARCHAR(60) NOT NULL,
    actif BOOLEAN NOT NULL,
    role VARCHAR(10) NOT NULL,
    client_id BIGINT UNIQUE REFERENCES client(id),
    perimetre_admin VARCHAR(10),
    zone_admin_id BIGINT REFERENCES zone(id),
    CONSTRAINT ck_compte_role CHECK (role IN ('CLIENT', 'ADMIN')),
    CONSTRAINT ck_compte_bcrypt CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
    CONSTRAINT ck_compte_profil CHECK (
        (role = 'CLIENT' AND client_id IS NOT NULL AND perimetre_admin IS NULL AND zone_admin_id IS NULL)
        OR (role = 'ADMIN' AND client_id IS NULL AND perimetre_admin IS NOT NULL AND (
            (perimetre_admin = 'GLOBAL' AND zone_admin_id IS NULL)
            OR (perimetre_admin = 'LOCAL' AND zone_admin_id IS NOT NULL)
        ))
    )
);
CREATE INDEX ix_compte_zone_admin ON compte(zone_admin_id);
