-- Socle de périodes uniquement. Aucun compte ni référentiel existant modifié.
-- Aucun archivage, transfert, droit de mutation ou verdict de disponibilité ajouté.
CREATE TABLE indisponibilite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT REFERENCES zone(id),
    vehicule_id BIGINT REFERENCES vehicule(id),
    debut TIMESTAMP WITH TIME ZONE NOT NULL,
    fin TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_indisponibilite_cible CHECK (
        (zone_id IS NOT NULL AND vehicule_id IS NULL)
        OR (zone_id IS NULL AND vehicule_id IS NOT NULL)
    ),
    CONSTRAINT ck_indisponibilite_periode CHECK (debut < fin)
);
CREATE INDEX ix_indisponibilite_zone_periode ON indisponibilite(zone_id,debut,fin)
    WHERE zone_id IS NOT NULL;
CREATE INDEX ix_indisponibilite_vehicule_periode ON indisponibilite(vehicule_id,debut,fin)
    WHERE vehicule_id IS NOT NULL;
