-- DriveConnect, cahier final, sections 7.1 et 19 : premiers référentiels.
-- Aucun compte, trajet ou paiement de démonstration n'est créé.
CREATE TABLE zone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL
);

CREATE TABLE client (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero TEXT NOT NULL CONSTRAINT uk_client_numero UNIQUE,
    categorie VARCHAR(20) NOT NULL,
    actif BOOLEAN NOT NULL,
    zone_id BIGINT REFERENCES zone(id),
    CONSTRAINT ck_client_categorie CHECK (categorie IN ('VIP', 'LOCAL', 'OCCASIONNEL')),
    CONSTRAINT ck_client_zone_locale CHECK (categorie <> 'LOCAL' OR zone_id IS NOT NULL)
);

CREATE TABLE vehicule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL REFERENCES zone(id)
);

CREATE INDEX ix_client_zone ON client(zone_id);
CREATE INDEX ix_vehicule_zone ON vehicule(zone_id);
