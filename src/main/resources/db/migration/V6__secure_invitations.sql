-- Aucun jeton brut ni compte créé. Historique conservé après expiration/consommation.
CREATE TABLE invitation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compte_id BIGINT NOT NULL REFERENCES compte(id),
    empreinte VARCHAR(64) NOT NULL CONSTRAINT uk_invitation_empreinte UNIQUE,
    cree_a TIMESTAMP WITH TIME ZONE NOT NULL,
    expire_a TIMESTAMP WITH TIME ZONE NOT NULL,
    consommee_a TIMESTAMP WITH TIME ZONE,
    revoquee_a TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_invitation_empreinte CHECK (empreinte ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_invitation_expiration CHECK (expire_a > cree_a),
    CONSTRAINT ck_invitation_consommation CHECK (
        consommee_a IS NULL OR (consommee_a >= cree_a AND consommee_a < expire_a)),
    CONSTRAINT ck_invitation_revocation CHECK (revoquee_a IS NULL OR revoquee_a >= cree_a),
    CONSTRAINT ck_invitation_terminale CHECK (consommee_a IS NULL OR revoquee_a IS NULL)
);
-- Une invitation expirée occupe encore ce créneau jusqu'à révocation/renouvellement.
CREATE UNIQUE INDEX uk_invitation_ouverte ON invitation(compte_id)
    WHERE consommee_a IS NULL AND revoquee_a IS NULL;
CREATE INDEX ix_invitation_compte_historique ON invitation(compte_id, cree_a);
